// Regenerate src/lib/api/schema.d.ts from the backend's OpenAPI schema: `npm run gen:api`.
// Reads the schema straight from the FastAPI app, so the backend needn't be running.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const backend = fileURLToPath(new URL("../../backend/", import.meta.url));
const python = fileURLToPath(
  new URL(process.platform === "win32" ? "../../.venv/Scripts/python.exe" : "../../.venv/bin/python", import.meta.url),
);
const out = fileURLToPath(new URL("../src/lib/api/schema.d.ts", import.meta.url));

const schema = execFileSync(
  python,
  ["-c", "import json, sys; from api.main import create_app; json.dump(create_app().openapi(), sys.stdout)"],
  { cwd: backend, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
);
const ast = await openapiTS(JSON.parse(schema));
writeFileSync(out, `// Generated by scripts/gen-api.mjs from the backend's OpenAPI schema. Do not edit.\n\n${astToString(ast)}`);
console.log(`wrote ${out}`);
